#!/usr/bin/env python3
"""Generate the binary64 constants of B64_Sin / B64_Cos from the Coq literals.

Reads every `Definition NAME : binary64 := Binary.B754_finite prec emax S M (E)`
used by b64_sin / b64_cos in theories-flocq/B64_SinPoly.v, B64_Sin.v,
B64_CosPoly.v, B64_ArcPoint.v, B64_FresnelPolyC/S.v, B64_Fresnel.v and B64_ClothoidMap.v, and
writes
  * the Extract Constant block of theories-flocq/Validate_binary64_extract.v
    (between the BEGIN/END b64_sin markers), as exact OCaml hex floats;
  * tests/B64SinConformance/B64SinConstants.g.cs, as exact IEEE bit patterns.
`--check` fails if either output is out of date.  One source, no hand copy.
"""
import re, struct, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = ["theories-flocq/B64_SinPoly.v", "theories-flocq/B64_Sin.v", "theories-flocq/B64_CosPoly.v",
       "theories-flocq/B64_ArcPoint.v", "theories-flocq/B64_FresnelPolyC.v", "theories-flocq/B64_FresnelPolyS.v",
       "theories-flocq/B64_Fresnel.v", "theories-flocq/B64_ClothoidMap.v"]
USED = ["sp_c%d" % k for k in range(11)] + ["cq_c%d" % k for k in range(12)] + [
    "sn_C1", "sn_C2", "sn_one", "sn_two", "sn_three",
    "sn_T1", "sn_T3", "sn_T5", "sn_ten", "sn_mten", "ap_cap", "ap_mcap"] + [
    "frc_c%d" % k for k in range(20)] + ["frs_c%d" % k for k in range(19)] + ["fr_X", "fr_mX", "cm_r2", "cm_Alo", "cm_cap", "cm_mcap"]
PAT = re.compile(r"Definition (\w+) : binary64 :=\s*Binary\.B754_finite prec emax "
                 r"(true|false) (\d+) \((-?\d+)\) eq_refl\.")

def literals():
    found = {}
    for f in SRC:
        mod = os.path.splitext(os.path.basename(f))[0]
        for m in PAT.finditer(open(os.path.join(ROOT, f)).read()):
            name, s, man, e = m.group(1), m.group(2) == "true", int(m.group(3)), int(m.group(4))
            v = man * 2.0 ** e           # exact: 53-bit mantissa, normal exponent
            assert int(v / 2.0 ** e) == man
            found[name] = (mod, -v if s else v)
    missing = [n for n in USED if n not in found]
    assert not missing, missing
    return [(n,) + found[n] for n in USED]

def bits(v):
    return struct.unpack("<Q", struct.pack("<d", v))[0]

def coq_block(lits):
    out = ["(* BEGIN b64_sin constants: generated by tests/B64SinConformance/gen_constants.py *)",
           "(* from the B754_finite literals; exact hex floats (the literal ctor is a stub). *)"]
    for n, mod, v in lits:
        h = v.hex()
        out.append('Extract Constant %s.%s => "(%s)".' % (mod, n, h))
    out.append("(* END b64_sin constants *)")
    return "\n".join(out) + "\n"

def cs_file(lits):
    out = ["// <auto-generated> by tests/B64SinConformance/gen_constants.py from the",
           "// Coq B754_finite literals of B64_SinPoly / B64_Sin / B64_CosPoly / B64_ArcPoint / B64_Fresnel* / B64_ClothoidMap.  Do not edit. </auto-generated>",
           "namespace NTS.Proofs.Numerics;", "",
           "internal static class B64SinConstants", "{"]
    for n, mod, v in lits:
        out.append("    internal static readonly double %s = System.BitConverter.Int64BitsToDouble(unchecked((long)0x%016XUL)); // %s"
                   % (n, bits(v), v.hex()))
    out.append("}")
    return "\n".join(out) + "\n"

def main():
    check = "--check" in sys.argv
    lits = literals()
    vfile = os.path.join(ROOT, "theories-flocq/Validate_binary64_extract.v")
    vs = open(vfile).read()
    a = vs.index("(* BEGIN b64_sin constants")
    b = vs.index("(* END b64_sin constants *)\n") + len("(* END b64_sin constants *)\n")
    new_vs = vs[:a] + coq_block(lits) + vs[b:]
    csf = os.path.join(ROOT, "tests/B64SinConformance/B64SinConstants.g.cs")
    new_cs = cs_file(lits)
    if check:
        old_cs = open(csf).read() if os.path.exists(csf) else ""
        if new_vs != vs or new_cs != old_cs:
            print("[b64-sin-constants] OUT OF DATE: run tests/B64SinConformance/gen_constants.py")
            sys.exit(1)
        print("[b64-sin-constants] OK: %d constants in sync" % len(lits)); return
    open(vfile, "w").write(new_vs); open(csf, "w").write(new_cs)
    print("[b64-sin-constants] wrote %d constants" % len(lits))

if __name__ == "__main__":
    main()
