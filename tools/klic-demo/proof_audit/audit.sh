#!/usr/bin/env bash
# Regenerate tools/klic-demo/proof_audit/print_assumptions.txt (repo root, after
# make -f Makefile.gen theories-flocq/HotPixel_Q_exec.vo NodingSeparation_b64.vo).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
d=tools/klic-demo/proof_audit
out=$d/print_assumptions.txt
{
  echo "# Print Assumptions, tools/klic-demo theorems.  $(rocq -v | head -1)"
  echo "# Generated by $d/audit.sh from $d/DemoAudit.v.  An Admitted lemma in any"
  echo "# chain would be listed here as an axiom bearing its own name; none is."
  echo
  rocq compile -Q theories NTS.Proofs -Q theories-flocq NTS.Proofs.Flocq $d/DemoAudit.v 2>&1 \
    | awk '/^Print Assumptions/{next} {print}'
} > "$out.tmp"
# label each block with its theorem (the probe prints them in file order);
# awk only, so this runs in the toolchain container (no python there)
names=$(grep -o 'Print Assumptions [^ ]*\.' $d/DemoAudit.v | sed 's/Print Assumptions //; s/\.$//')
awk -v names="$names" 'BEGIN{n=split(names,N,"\n"); i=0}
  /^Axioms:/ || /^Closed under the global context/ {i++; print "== " N[i]}
  {print}
  END{if (i!=n) {print "label mismatch " i " vs " n > "/dev/stderr"; exit 1}}' "$out.tmp" > "$out"
rm -f "$out.tmp" $d/DemoAudit.vo $d/DemoAudit.vok $d/DemoAudit.vos $d/DemoAudit.glob $d/.DemoAudit.aux
echo "wrote $out"
