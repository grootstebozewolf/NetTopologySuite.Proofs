module Z =
 struct
  (** val double : z -> z **)

  let double = function
  | Z0 -> Z0
  | Zpos p -> Zpos (XO p)
  | Zneg p -> Zneg (XO p)

  (** val succ_double : z -> z **)

  let succ_double = function
  | Z0 -> Zpos XH
  | Zpos p -> Zpos (XI p)
  | Zneg p -> Zneg (Pos.pred_double p)

  (** val pred_double : z -> z **)

  let pred_double = function
  | Z0 -> Zneg XH
  | Zpos p -> Zpos (Pos.pred_double p)
  | Zneg p -> Zneg (XI p)

  (** val pos_sub : positive -> positive -> z **)

  let rec pos_sub x y =
    match x with
    | XI p ->
      (match y with
       | XI q0 -> double (pos_sub p q0)
       | XO q0 -> succ_double (pos_sub p q0)
       | XH -> Zpos (XO p))
    | XO p ->
      (match y with
       | XI q0 -> pred_double (pos_sub p q0)
       | XO q0 -> double (pos_sub p q0)
       | XH -> Zpos (Pos.pred_double p))
    | XH ->
      (match y with
       | XI q0 -> Zneg (XO q0)
       | XO q0 -> Zneg (Pos.pred_double q0)
       | XH -> Z0)

  (** val add : z -> z -> z **)

  let add x y =
    match x with
    | Z0 -> y
    | Zpos x' ->
      (match y with
       | Z0 -> x
       | Zpos y' -> Zpos (Pos.add x' y')
       | Zneg y' -> pos_sub x' y')
    | Zneg x' ->
      (match y with
       | Z0 -> x
       | Zpos y' -> pos_sub y' x'
       | Zneg y' -> Zneg (Pos.add x' y'))

  (** val opp : z -> z **)

  let opp = function
  | Z0 -> Z0
  | Zpos x0 -> Zneg x0
  | Zneg x0 -> Zpos x0

  (** val sub : z -> z -> z **)

  let sub m n =
    add m (opp n)

  (** val mul : z -> z -> z **)

  let mul x y =
    match x with
    | Z0 -> Z0
    | Zpos x' ->
      (match y with
       | Z0 -> Z0
       | Zpos y' -> Zpos (Pos.mul x' y')
       | Zneg y' -> Zneg (Pos.mul x' y'))
    | Zneg x' ->
      (match y with
       | Z0 -> Z0
       | Zpos y' -> Zneg (Pos.mul x' y')
       | Zneg y' -> Zpos (Pos.mul x' y'))

  (** val compare : z -> z -> comparison **)

  let compare x y =
    match x with
    | Z0 -> (match y with
             | Z0 -> Eq
             | Zpos _ -> Lt
             | Zneg _ -> Gt)
    | Zpos x' -> (match y with
                  | Zpos y' -> Pos.compare x' y'
                  | _ -> Gt)
    | Zneg x' ->
      (match y with
       | Zneg y' -> compOpp (Pos.compare x' y')
       | _ -> Lt)

  (** val leb : z -> z -> bool **)

  let leb x y =
    match compare x y with
    | Gt -> False
    | _ -> True

  (** val ltb : z -> z -> bool **)

  let ltb x y =
    match compare x y with
    | Lt -> True
    | _ -> False

  (** val eqb : z -> z -> bool **)

  let eqb x y =
    match x with
    | Z0 -> (match y with
             | Z0 -> True
             | _ -> False)
    | Zpos p -> (match y with
                 | Zpos q0 -> Pos.eqb p q0
                 | _ -> False)
    | Zneg p -> (match y with
                 | Zneg q0 -> Pos.eqb p q0
                 | _ -> False)

  (** val of_nat : nat -> z **)

  let of_nat = function
  | O -> Z0
  | S n0 -> Zpos (Pos.of_succ_nat n0)

  (** val to_pos : z -> positive **)

  let to_pos = function
  | Zpos p -> p
  | _ -> XH

  (** val pos_div_eucl : positive -> z -> (z, z) prod **)

  let rec pos_div_eucl a b =
    match a with
    | XI a' ->
      let Pair (q0, r) = pos_div_eucl a' b in
      let r' = add (mul (Zpos (XO XH)) r) (Zpos XH) in
      (match ltb r' b with
       | True -> Pair ((mul (Zpos (XO XH)) q0), r')
       | False -> Pair ((add (mul (Zpos (XO XH)) q0) (Zpos XH)), (sub r' b)))
    | XO a' ->
      let Pair (q0, r) = pos_div_eucl a' b in
      let r' = mul (Zpos (XO XH)) r in
      (match ltb r' b with
       | True -> Pair ((mul (Zpos (XO XH)) q0), r')
       | False -> Pair ((add (mul (Zpos (XO XH)) q0) (Zpos XH)), (sub r' b)))
    | XH ->
      (match leb (Zpos (XO XH)) b with
       | True -> Pair (Z0, (Zpos XH))
       | False -> Pair ((Zpos XH), Z0))

  (** val div_eucl : z -> z -> (z, z) prod **)

  let div_eucl a b =
    match a with
    | Z0 -> Pair (Z0, Z0)
    | Zpos a' ->
      (match b with
       | Z0 -> Pair (Z0, a)
       | Zpos _ -> pos_div_eucl a' b
       | Zneg b' ->
         let Pair (q0, r) = pos_div_eucl a' (Zpos b') in
         (match r with
          | Z0 -> Pair ((opp q0), Z0)
          | _ -> Pair ((opp (add q0 (Zpos XH))), (add b r))))
    | Zneg a' ->
      (match b with
       | Z0 -> Pair (Z0, a)
       | Zpos _ ->
         let Pair (q0, r) = pos_div_eucl a' b in
         (match r with
          | Z0 -> Pair ((opp q0), Z0)
          | _ -> Pair ((opp (add q0 (Zpos XH))), (sub b r)))
       | Zneg b' ->
         let Pair (q0, r) = pos_div_eucl a' (Zpos b') in Pair (q0, (opp r)))

  (** val div : z -> z -> z **)

  let div a b =
    let Pair (q0, _) = div_eucl a b in q0

  (** val modulo : z -> z -> z **)

  let modulo a b =
    let Pair (_, r) = div_eucl a b in r

  (** val even : z -> bool **)

  let even = function
  | Z0 -> True
  | Zpos p -> (match p with
               | XO _ -> True
               | _ -> False)
  | Zneg p -> (match p with
               | XO _ -> True
               | _ -> False)

  (** val sgn : z -> z **)

  let sgn = function
  | Z0 -> Z0
  | Zpos _ -> Zpos XH
  | Zneg _ -> Zneg XH

  (** val abs : z -> z **)

  let abs = function
  | Zneg p -> Zpos p
  | x -> x

  (** val ggcd : z -> z -> (z, (z, z) prod) prod **)

  let ggcd a b =
    match a with
    | Z0 -> Pair ((abs b), (Pair (Z0, (sgn b))))
    | Zpos a0 ->
      (match b with
       | Z0 -> Pair ((abs a), (Pair ((sgn a), Z0)))
       | Zpos b0 ->
         let Pair (g, p) = Coq_Pos.ggcd a0 b0 in
         let Pair (aa, bb) = p in
         Pair ((Zpos g), (Pair ((Zpos aa), (Zpos bb))))
       | Zneg b0 ->
         let Pair (g, p) = Coq_Pos.ggcd a0 b0 in
         let Pair (aa, bb) = p in
         Pair ((Zpos g), (Pair ((Zpos aa), (Zneg bb)))))
    | Zneg a0 ->
      (match b with
       | Z0 -> Pair ((abs a), (Pair ((sgn a), Z0)))
       | Zpos b0 ->
         let Pair (g, p) = Coq_Pos.ggcd a0 b0 in
         let Pair (aa, bb) = p in
         Pair ((Zpos g), (Pair ((Zneg aa), (Zpos bb))))
       | Zneg b0 ->
         let Pair (g, p) = Coq_Pos.ggcd a0 b0 in
         let Pair (aa, bb) = p in
         Pair ((Zpos g), (Pair ((Zneg aa), (Zneg bb)))))
 end

type q = { qnum : z; qden : positive }

(** val inject_Z : z -> q **)

let inject_Z x =
  { qnum = x; qden = XH }

(** val qeq_bool : q -> q -> bool **)

let qeq_bool x y =
  Z.eqb (Z.mul x.qnum (Zpos y.qden)) (Z.mul y.qnum (Zpos x.qden))

(** val qle_bool : q -> q -> bool **)

let qle_bool x y =
  Z.leb (Z.mul x.qnum (Zpos y.qden)) (Z.mul y.qnum (Zpos x.qden))

(** val qplus : q -> q -> q **)

let qplus x y =
  { qnum = (Z.add (Z.mul x.qnum (Zpos y.qden)) (Z.mul y.qnum (Zpos x.qden)));
    qden = (Coq_Pos.mul x.qden y.qden) }

(** val qmult : q -> q -> q **)

let qmult x y =
  { qnum = (Z.mul x.qnum y.qnum); qden = (Coq_Pos.mul x.qden y.qden) }

(** val qopp : q -> q **)

let qopp x =
  { qnum = (Z.opp x.qnum); qden = x.qden }

(** val qminus : q -> q -> q **)

let qminus x y =
  qplus x (qopp y)

(** val qinv : q -> q **)

let qinv x =
  match x.qnum with
  | Z0 -> { qnum = Z0; qden = XH }
  | Zpos p -> { qnum = (Zpos x.qden); qden = p }
  | Zneg p -> { qnum = (Zneg x.qden); qden = p }

(** val qdiv : q -> q -> q **)

let qdiv x y =
  qmult x (qinv y)

(** val qred : q -> q **)

let qred q0 =
  let { qnum = q1; qden = q2 } = q0 in
  let Pair (r1, r2) = snd (Z.ggcd q1 (Zpos q2)) in
  { qnum = r1; qden = (Z.to_pos r2) }

(** val q_min : q -> q -> q **)

let q_min a b =
  match qle_bool a b with
  | True -> a
  | False -> b

(** val q_max : q -> q -> q **)

let q_max a b =
  match qle_bool a b with
  | True -> b
  | False -> a

(** val q_round_ne : q -> z **)

let q_round_ne q0 =
  let n = q0.qnum in
  let d = Zpos q0.qden in
  let f = Z.div n d in
  let r = Z.modulo n d in
  (match Z.compare (Z.mul (Zpos (XO XH)) r) d with
   | Eq -> (match Z.even f with
            | True -> f
            | False -> Z.add f (Zpos XH))
   | Lt -> f
   | Gt -> Z.add f (Zpos XH))

(** val q_snap_coord : q -> q -> q **)

let q_snap_coord x s =
  qdiv (inject_Z (q_round_ne (qmult x s))) s

type qPoint = { qx : q; qy : q }

(** val q_snap : qPoint -> q -> qPoint **)

let q_snap p s =
  { qx = (q_snap_coord p.qx s); qy = (q_snap_coord p.qy s) }

(** val q_snap_disp : q -> q -> q **)

let q_snap_disp x s =
  let d = qminus (q_snap_coord x s) x in q_max d (qopp d)

(** val q_axis : q -> q -> q -> q -> (q, q) prod option **)

let q_axis c0 c1 lo hi =
  match qeq_bool c1 c0 with
  | True ->
    (match match qle_bool lo c0 with
           | True -> qle_bool c0 hi
           | False -> False with
     | True ->
       Some (Pair ({ qnum = Z0; qden = XH }, { qnum = (Zpos XH); qden = XH }))
     | False -> None)
  | False ->
    let a = qdiv (qminus lo c0) (qminus c1 c0) in
    let b = qdiv (qminus hi c0) (qminus c1 c0) in
    Some (Pair ((q_min a b), (q_max a b)))

(** val q_hot_pixel_radius : q -> q **)

let q_hot_pixel_radius s =
  qinv (qmult { qnum = (Zpos (XO XH)); qden = XH } s)

(** val q_touches_closed : qPoint -> qPoint -> qPoint -> q -> bool **)

let q_touches_closed p0 p1 c s =
  let r = q_hot_pixel_radius s in
  (match q_axis p0.qx p1.qx (qminus c.qx r) (qplus c.qx r) with
   | Some p ->
     let Pair (lx, hx) = p in
     (match q_axis p0.qy p1.qy (qminus c.qy r) (qplus c.qy r) with
      | Some p2 ->
        let Pair (ly, hy) = p2 in
        qle_bool (q_max { qnum = Z0; qden = XH } (q_max lx ly))
          (q_min { qnum = (Zpos XH); qden = XH } (q_min hx hy))
      | None -> False)
   | None -> False)

(** val q_passes_through_closed : qPoint -> qPoint -> qPoint -> q -> bool **)

let q_passes_through_closed p0 p1 c s =
  match q_touches_closed p0 p1 c s with
  | True -> q_touches_closed (q_snap p0 s) (q_snap p1 s) c s
  | False -> False

(** val q_seg_intersection :
    qPoint -> qPoint -> qPoint -> qPoint -> qPoint option **)

let q_seg_intersection p0 p1 q0 q1 =
  let dx = qminus p1.qx p0.qx in
  let dy = qminus p1.qy p0.qy in
  let ex = qminus q1.qx q0.qx in
  let ey = qminus q1.qy q0.qy in
  let wx = qminus q0.qx p0.qx in
  let wy = qminus q0.qy p0.qy in
  let den = qminus (qmult dx ey) (qmult dy ex) in
  (match qeq_bool den { qnum = Z0; qden = XH } with
   | True -> None
   | False ->
     let t = qdiv (qminus (qmult wx ey) (qmult wy ex)) den in
     let u = qdiv (qminus (qmult wx dy) (qmult wy dx)) den in
     (match match match qle_bool { qnum = Z0; qden = XH } t with
                  | True -> qle_bool t { qnum = (Zpos XH); qden = XH }
                  | False -> False with
            | True ->
              (match qle_bool { qnum = Z0; qden = XH } u with
               | True -> qle_bool u { qnum = (Zpos XH); qden = XH }
               | False -> False)
            | False -> False with
      | True ->
        Some { qx = (qplus p0.qx (qmult t dx)); qy =
